/**
 * An operating system distro icon, drawn in the same pencil-sketch style as
 * `Flag`: with jitter displacement noise and soft ink transparency.
 */
export function OsIcon({
  os,
  className,
  size = 24,
  variant = "stamp",
  title,
}: {
  os?: string
  className?: string
  size?: number
  variant?: "stamp" | "inline"
  title?: string
}) {
  const distro = detectDistro(os)
  const filterId = `os-filter-${useId().replace(/[^a-zA-Z0-9_-]/g, "")}`
  if (!distro) return null

  const displayTitle = title ?? distroTitle(distro)

  if (variant === "inline") {
    return (
      <svg
        className={`os-inline ${className ?? ""}`}
        viewBox="0 0 24 24"
        width={size}
        height={size}
        aria-label={displayTitle}
        style={{ display: "inline-block", verticalAlign: "-0.15em", flex: "none" }}
      >
        <title>{displayTitle}</title>
        <DistroGlyph distro={distro} />
      </svg>
    )
  }

  return (
    <div title={displayTitle} style={{ display: "inline-flex" }}>
      <SketchBox
        className={className ?? "card-os"}
        seedKey={`os-box-${distro}`}
        radius={3}
        strokeWidth={1.2}
      >
        <svg className="os-ink" viewBox="0 0 24 24" aria-hidden="true">
          <filter id={filterId} x="-15%" y="-15%" width="130%" height="130%">
            <feTurbulence type="fractalNoise" baseFrequency="0.07 0.1" numOctaves="2" seed="17" result="warp" />
            <feDisplacementMap in="SourceGraphic" in2="warp" scale="1.8" xChannelSelector="R" yChannelSelector="G" />
          </filter>
          <g filter={`url(#${filterId})`}>
            <DistroGlyph distro={distro} />
          </g>
        </svg>
      </SketchBox>
    </div>
  )
}
