export function detectDistro(osStr?: string): DistroKey | null {
  if (!osStr) return null
  const s = osStr.toLowerCase()
  if (s.includes("armbian")) return "armbian"
  if (s.includes("debian")) return "debian"
  if (s.includes("ubuntu")) return "ubuntu"
  if (s.includes("arch")) return "arch"
  if (s.includes("alpine")) return "alpine"
  if (s.includes("rocky")) return "rocky"
  if (s.includes("alma")) return "alma"
  if (s.includes("centos")) return "centos"
  if (s.includes("fedora")) return "fedora"
  if (s.includes("suse")) return "opensuse"
  if (s.includes("red hat") || s.includes("rhel")) return "redhat"
  if (s.includes("windows")) return "windows"
  if (s.includes("darwin") || s.includes("macos") || s.includes("os x") || s.includes("apple")) return "apple"
  if (s.includes("freebsd") || s.includes("bsd")) return "freebsd"
  if (s.includes("linux")) return "linux"
  return null
}

